#include "route_model.h"
#include <cassert>
#include <fstream>
#include <iterator>
#include <iostream>
int main(int argc, char** argv) {
    assert(argc == 2);
    std::ifstream input(argv[1]);
    std::string data((std::istreambuf_iterator<char>(input)), {});
    route_ui::Route route;
    assert(route_ui::Parse(data, route));
    assert(route.legs.size() == 2 && route.minutes == 25);
    assert(route.legs[0].from == "光が丘" && route.legs[1].to == "池袋");
    assert(route.legs[0].color == 0xB6007A);
    auto reject = [&](std::string invalid) {
        assert(!route_ui::Parse(invalid, route));
        assert(route.legs.size() == 2 && route.legs[0].from == "光が丘");
    };
    reject(""); reject(data + "garbage"); reject(data.substr(0, data.size()-1));
    reject(std::string(16385, ' '));
    reject(std::string(100, '[') + std::string(100, ']'));
    for (auto replacement : {"-1", "1.5", "100000", "1e999", "\"25\""}) {
        auto invalid = data; auto pos = invalid.find("\"minutes\":25");
        invalid.replace(pos, 12, std::string("\"minutes\":") + replacement); reject(invalid);
    }
    for (const auto& name : std::vector<std::string>{"", "a\\u0000b", "a\\nb", "a\\u007fb", std::string(257,'a')}) {
        auto invalid = data; invalid.replace(invalid.find("光が丘"), std::strlen("光が丘"), name); reject(invalid);
    }
    auto invalid = data; invalid.replace(invalid.find("B6007A"), 6, "zzzzzz"); reject(invalid);
    // Derive boundary fixtures from the same JSON generated by the Node encoder.
    auto fixture = [&](int version, int count, const char* minutes) {
        std::unique_ptr<cJSON, decltype(&cJSON_Delete)> json(cJSON_Parse(data.c_str()), cJSON_Delete);
        cJSON_SetNumberValue(cJSON_GetObjectItemCaseSensitive(json.get(), "version"), version);
        cJSON_ReplaceItemInObjectCaseSensitive(json.get(), "minutes", cJSON_Parse(minutes));
        auto original = cJSON_GetObjectItemCaseSensitive(json.get(), "legs");
        auto legs = cJSON_CreateArray();
        for (int i=0; i<count; ++i) cJSON_AddItemToArray(legs, cJSON_Duplicate(cJSON_GetArrayItem(original, 0), true));
        cJSON_ReplaceItemInObjectCaseSensitive(json.get(), "legs", legs);
        char* encoded = cJSON_PrintUnformatted(json.get());
        std::string result(encoded); cJSON_free(encoded); return result;
    };
    reject(fixture(0,2,"25")); reject(fixture(2,2,"25"));
    reject(fixture(1,0,"25")); reject(fixture(1,31,"25"));
    for (const char* minutes : {"null", "0", "99999"}) {
        route_ui::Route accepted;
        assert(route_ui::Parse(fixture(1,30,minutes), accepted));
        assert(accepted.legs.size()==30);
        assert(accepted.minutes==(std::string(minutes)=="null" ? -1 : std::stoi(minutes)));
    }
    for (int n : {1, 2, 30}) {
        int page = 0;
        for (int i = 1; i <= n; ++i) { page=route_ui::Next(page,n); assert(page==i); }
        assert(route_ui::Next(page,n)==0);
        for (int i = n-1; i >= 0; --i) { page=route_ui::Previous(page); assert(page==i); }
    }
    std::cout << "Route parser and navigation passed\n";
}
